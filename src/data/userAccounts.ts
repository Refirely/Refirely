export const getWorldCountryFlag = (countryName?: string): string => {
  if (!countryName) return '🌍';
  const match = WORLD_COUNTRIES.find(c => c.name.toLowerCase() === countryName.trim().toLowerCase());
  return match?.flag || '🌍';
};

