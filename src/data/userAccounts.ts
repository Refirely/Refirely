export const formatLocalCurrency = (amountUSD: number, macro: CountryCurrencyMacro, compact = false): string => {
  const localVal = Math.round(amountUSD * macro.rateToUSD);
  if (macro.currencyCode === 'INR') {
    const absVal = Math.abs(localVal);
    const sign = localVal < 0 ? '-' : '';
    if (compact && absVal >= 10000000) {
      return `${sign}₹${(absVal / 10000000).toFixed(2)} Cr`;
    }
    if (compact && absVal >= 100000) {
      return `${sign}₹${(absVal / 100000).toFixed(2)} L`;
    }
    return `${sign}₹${absVal.toLocaleString('en-IN')}`;
  }

  if (compact && Math.abs(localVal) >= 1000000) {
    return `${macro.symbol}${(localVal / 1000000).toFixed(2)}M ${macro.currencyCode}`;
  }
  return `${macro.symbol}${localVal.toLocaleString()} ${macro.currencyCode}`;
};

export const formatDualCurrency = (amountUSD: number, macro: CountryCurrencyMacro, compact = true): string => {
  const usdFormatted = `$${Math.round(amountUSD).toLocaleString()}`;
  if (macro.currencyCode === 'USD') {
    return `${usdFormatted} USD`;
  }
  return `${formatLocalCurrency(amountUSD, macro, compact)} (${usdFormatted} USD)`;
};

